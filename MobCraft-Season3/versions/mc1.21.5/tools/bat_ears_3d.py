"""Builds the 3D helmet bat ears from bat_ears.png.
Every pixel of the ear becomes a small block. The dark back is one layer of blocks.
In front of it, each pixel sticks out further the closer it is to the ear's edge,
so the rim stands tall and the pink middle sits deep inside: a cupped ear made of voxels.
The ear is thickest at the bottom and thins toward the tip.
Each pixel row is its own piece. Going up, the rows bend forward along a curve that starts
gently and tightens near the tip, so the ear curls forward almost over itself.
Writes textures/entity/bat_ears_3d.png (one solid swatch per colour) and BatEarModel.java.
Usage: bat_ears_3d.py <mod source root>"""
import sys, pathlib
from PIL import Image
root = pathlib.Path(sys.argv[1])
tex = root / 'src/main/resources/assets/mobcraft/textures/entity'
src = Image.open(tex / 'bat_ears.png').convert('RGBA')
DEPTH = {0: 8, 1: 6, 2: 4}   # quarter-pixels forward of the back layer by ring: edge, next ring, then middle
INNER = 2
TOP = 0.55                    # the top of the ear is this much as deep as the bottom, like a human ear
CURL = 35                     # degrees the tip has turned forward from the base
CURL_POWER = 2.0              # higher starts the bend later and makes it sharper near the tip

palette = []
def colour(p):
    if p not in palette: palette.append(p)
    return palette.index(p)

def picture(x0, row):
    return [[src.getpixel((x0 + c, row + r)) for c in range(10)] for r in range(15)]

def rings(pic):
    W, H = 10, 15
    INF = 99
    d = [[INF if pic[r][c][3] else -1 for c in range(W)] for r in range(H)]
    frontier = []
    for r in range(H):
        for c in range(W):
            if d[r][c] < 0: continue
            for dr, dc in ((1,0),(-1,0),(0,1),(0,-1)):
                rr, cc = r+dr, c+dc
                if not (0 <= rr < H and 0 <= cc < W) or pic[rr][cc][3] == 0:
                    d[r][c] = 0; frontier.append((r, c)); break
    while frontier:
        nxt = []
        for r, c in frontier:
            for dr, dc in ((1,0),(-1,0),(0,1),(0,-1)):
                rr, cc = r+dr, c+dc
                if 0 <= rr < H and 0 <= cc < W and d[rr][cc] > d[r][c] + 1:
                    d[rr][cc] = d[r][c] + 1; nxt.append((rr, cc))
        frontier = nxt
    return d

def boxes(row):
    inside = picture(0, row)
    outside = picture(30, row)           # seen from behind, so world column c shows outside column 9-c
    ring = rings(inside)
    cells = []                           # (y, x, z0, dz, colour); y and x in half-units, z in quarters
    for r in range(15):
        for c in range(10):
            o = outside[r][9 - c]
            if o[3]: cells.append((r, c, 0, 2, colour(o[:3])))
            p = inside[r][c]
            if p[3]:
                taper = TOP + (1 - TOP) * r / 14
                dz = max(1, round(DEPTH.get(ring[r][c], INNER) * taper))
                cells.append((r, c, -dz, dz, colour(p[:3])))
    # join neighbours in a row that match, to keep the box count down
    cells.sort(key=lambda t: (t[0], t[2], t[3], t[4], t[1]))
    out = []
    for y, x, z0, dz, col in cells:
        if out and out[-1][0] == y and out[-1][2] == z0 and out[-1][3] == dz and out[-1][5] == col \
                and out[-1][1] + out[-1][4] == x:
            out[-1][4] += 1
        else:
            out.append([y, x, z0, dz, 1, col])
    return out

import math
def bend():
    """Each row's hinge (y, z on the ear's back surface) and its forward turn, bottom row first."""
    out = {}
    y = z = 0.0
    for i in range(15):                  # i = 0 is the bottom row (picture row 14)
        mid = (i + 0.5) / 15
        a = math.radians(CURL) * mid ** CURL_POWER
        out[14 - i] = (y, z, a)
        y -= 0.5 * math.cos(a)
        z -= 0.5 * math.sin(a)
    return out

left, right = boxes(0), boxes(16)
ROWS = bend()
assert len(palette) <= 32, len(palette)
img = Image.new('RGBA', (64, 32), (0, 0, 0, 0))
for i, p in enumerate(palette):
    img.paste(p + (255,), (16 * (i % 4), 4 * (i // 4), 16 * (i % 4) + 16, 4 * (i // 4) + 4))
img.save(tex / 'bat_ears_3d.png')

def arr(bs):
    return ',\n            '.join('{%d, %d, %d, %d, %d, %d}' % (y, x, z0, dz, w, col) for y, x, z0, dz, w, col in bs)

java = root / 'src/main/java/com/reality/mobcraft/client/BatEarModel.java'
rows = ',\n            '.join('{%sf, %sf, %sf}' % (round(ROWS[r][0], 4), round(ROWS[r][1], 4), round(ROWS[r][2], 4)) for r in range(15))
java.write_text(f'''package com.reality.mobcraft.client;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.PartDefinition;

/**
 * The helmet's 3D bat ears, one small block per pixel of bat_ears.png.
 * Generated by tools/bat_ears_3d.py; edit the script, not this file.
 * Each row is y, x, z, depth, width, colour: y, x and width in half-pixels, z and depth in quarter-pixels.
 * bat_ears_3d.png holds one solid 16x4 swatch per colour, so every face of a block is that colour.
 */
final class BatEarModel {{
    static final int TEXTURE_WIDTH = 64;
    static final int TEXTURE_HEIGHT = 32;

    private static final int[][] LEFT = {{
            {arr(left)}
    }};
    private static final int[][] RIGHT = {{
            {arr(right)}
    }};
    /** Per picture row, top first: the hinge's y and z on the ear's back surface, and its forward turn. */
    private static final float[][] ROWS = {{
            {rows}
    }};

    private BatEarModel() {{
    }}

    /**
     * Adds one ear's rows under the given part. The ear's base is at y 0 and its back surface at z 0.5;
     * the pink side faces -z. Each row hinges on the back surface, so the back stays closed as it bends.
     */
    static void addEar(PartDefinition parent, boolean left) {{
        CubeListBuilder[] rows = new CubeListBuilder[ROWS.length];
        for (int r = 0; r < rows.length; r++) rows[r] = CubeListBuilder.create();
        for (int[] b : left ? LEFT : RIGHT) {{
            rows[b[0]].texOffs(16 * (b[5] % 4), 4 * (b[5] / 4))
                    .addBox(-2.5f + b[1] * 0.5f, -0.5f, b[2] * 0.25f - 0.5f, b[4] * 0.5f, 0.5f, b[3] * 0.25f);
        }}
        for (int r = 0; r < rows.length; r++) {{
            parent.addOrReplaceChild("mobcraft_ear_row_" + r, rows[r],
                    PartPose.offsetAndRotation(0f, ROWS[r][0], ROWS[r][1] + 0.5f, ROWS[r][2], 0f, 0f));
        }}
    }}
}}
''')
print(len(palette), 'colours,', len(left), len(right), 'boxes')
